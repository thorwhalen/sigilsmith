describe('CLI surface (--json envelope, exit codes)', () => {
  beforeAll(() => {
    if (!existsSync(CLI)) execFileSync('npx', ['tsup'], { cwd: new URL('..', import.meta.url).pathname });
  });
  const run = (args: string[], cwd: string) => spawnSync('node', [CLI, ...args], { cwd, encoding: 'utf8' });
  it('check --json prints one envelope and exits 0 / 1', async () => {
    const dir = makeProject(BASIC);
    expect(run(['build', '--json'], dir).status).toBe(0);
    const ok = run(['check', '--json'], dir);
    expect(JSON.parse(ok.stdout)).toMatchObject({ schema: 'sigilsmith.check/1', ok: true });
    expect(ok.status).toBe(0);
    writeFileSync(join(dir, 'items.json'), JSON.stringify([{ uid: 1 }, { uid: 2 }]));
    const bad = run(['check', '--json', '--only', 'data'], dir);
    expect(bad.status).toBe(1);
    expect(JSON.parse(bad.stdout).diagnostics[0].code).toBe('SGS0701');
  });
  it('exit 3 without a config, 2 on usage errors; explain-code answers offline', () => {
    const dir = makeProject(BASIC);
    expect(run(['check', '--config', 'missing.json', '--json'], dir).status).toBe(3);
    expect(run(['frobnicate'], dir).status).toBe(2);
    expect(JSON.parse(run(['explain-code', 'SGS0701', '--json'], dir).stdout).data.title).toBe('key field missing from data');
  });
  it('build with invalid params prints the diagnostics, not an internal error (#14)', () => {
    const dir = makeProject({ ...BASIC, generators: { 'grid@1': { params: { cells: 42 } } } });
    const r = run(['build'], dir);
    expect(r.status).toBe(1);
    expect(r.stderr).toContain('SGS0302');
    expect(r.stderr).not.toContain('internal error');
  });
  it('detect-key --write records the key in the config', () => {
    const dir = makeProject({ ...BASIC, key: { field: 'wrong' } }, [{ slug: 'a', type: 'video' }, { slug: 'b', type: 'audio' }]);
    const r = run(['detect-key', 'items.json', '--write', '--json'], dir);
    expect(JSON.parse(r.stdout).data.written).toBe(true);
    expect(JSON.parse(readFileSync(join(dir, 'sigilsmith.config.json'), 'utf8')).key.field).toBe('slug');
  });
});

describe('service terms (DiceBear, SGS0107)', () => {
  it('warns until the terms are acknowledged or a self-hosted baseUrl is set; the catalog shows them', async () => {
    const base = { ...BASIC, policy: { default: 'grid@1', rules: [{ when: { type: 'video' }, use: 'avatar@9' }] } };
    const warn = await loadConfig(undefined, makeProject({ ...base, remote: { 'avatar@9': { transport: 'dicebear' } } }));
    expect(warn.diagnostics).toEqual([expect.objectContaining({ code: 'SGS0107', severity: 'warning' })]);
    const ack = await loadConfig(undefined, makeProject({ ...base, remote: { 'avatar@9': { transport: 'dicebear', use: 'non-commercial' } } }));
    expect(ack.diagnostics).toEqual([expect.objectContaining({ code: 'SGS0107', severity: 'info' })]);
    const own = await loadConfig(undefined, makeProject({ ...base, remote: { 'avatar@9': { transport: 'dicebear', baseUrl: 'https://avatars.example.com' } } }));
    expect(own.diagnostics).toEqual([]);
    const row = catalog({ implemented: true }).data.results.find((r) => r.id === 'dicebear-http-api')!;
    expect(row.terms![0]).toMatch(/NON-COMMERCIAL/);
    expect(row.usage).toContain('"transport": "dicebear"');
  });
});

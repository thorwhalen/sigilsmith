import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import { build, catalog, check, detectKey, explainItems, loadConfig, ManifestSchema } from '../src/node/index.js';
import { BASIC, makeProject, SAMPLE_ITEMS } from './project.js';

const CLI = new URL('../dist/cli/main.js', import.meta.url).pathname;

describe('schemas (B10, B0.2)', () => {
  it('every catalog draft validates against the manifest schema', () => {
    const dir = new URL('../catalog/', import.meta.url).pathname;
    const files = readdirSync(dir).filter((f) => f.endsWith('.json') && !f.startsWith('_'));
    expect(files.length).toBeGreaterThan(50);
    const bad = files.filter((f) => !ManifestSchema.safeParse(JSON.parse(readFileSync(dir + f, 'utf8'))).success);
    expect(bad).toEqual([]);
  });
  it('reports schema errors with a path, and refuses secrets and unknown refs', async () => {
    const dir = makeProject({ ...BASIC, policy: { default: 'nope@1' }, remote: { 'ai@1': { transport: 'proxy', url: 'sk-abcdefghijklmnop' } } });
    const loaded = await loadConfig(undefined, dir);
    const codes = loaded.diagnostics.map((d) => d.code);
    expect(codes).toContain('SGS0104');
    expect(codes).toContain('SGS0105');
    const bad = makeProject({ key: { field: 'id' }, policy: { default: 'grid@1' }, delivery: { strategy: 'sometimes' } });
    const l2 = await loadConfig(undefined, bad);
    expect(l2.diagnostics[0]).toMatchObject({ code: 'SGS0102', where: { path: 'delivery.strategy' } });
  });
  it('validates generator params against the manifest', async () => {
    const dir = makeProject({ ...BASIC, generators: { 'grid@1': { params: { cells: 42 } } } });
    const loaded = await loadConfig(undefined, dir);
    expect(loaded.diagnostics).toEqual([expect.objectContaining({ code: 'SGS0302', where: expect.objectContaining({ path: 'generators.grid@1.params.cells' }) })]);
  });
});

describe('catalog query (B11)', () => {
  it('filters by constraints and says why others were excluded', () => {
    const env = catalog({ style: ['abstract'], noNetwork: true, maxGzip: 1000, implemented: true });
    expect(env.data.results.map((r) => r.ref).sort()).toEqual(['rings@1', 'shapes@1']);
    expect(env.data.excluded.find((e) => e.id === 'grid@1')!.because).toMatch(/style geometric/);
    expect(env.data.results[0]!.measured).toBe(true);
  });
});

describe('detect-key (B4.1)', () => {
  it('prefers explicit ids and reports completeness and uniqueness', () => {
    const r = detectKey([{ slug: 'a', title: 'A' }, { slug: 'b', title: 'B' }]);
    expect(r.chosen!.key).toEqual({ field: 'slug' });
    expect(r.chosen!.uniqueness).toBe(1);
  });
  it('flags unstable keys and proposes the smallest unique composite', () => {
    const r = detectKey([
      { artist: 'A', title: 'X', year: 1990 },
      { artist: 'A', title: 'Y', year: 1990 },
      { artist: 'B', title: 'X', year: 1991 },
    ]);
    expect(r.chosen!.key).toEqual({ fields: expect.arrayContaining(['artist', 'title']) });
    expect(r.candidates.length).toBeGreaterThan(0);
  });
  it('warns when the only unique field is display text', () => {
    const r = detectKey([{ title: 'A song' }, { title: 'B song' }]);
    expect(r.warnings.join(' ')).toMatch(/display text/);
  });
});

describe('build, explain and check end to end', () => {
  let dir: string;
  beforeAll(async () => {
    dir = makeProject(BASIC);
    const loaded = await loadConfig(undefined, dir);
    expect(loaded.diagnostics).toEqual([]);
    const env = await build(loaded);
    expect(env.ok).toBe(true);
  });

  it('writes a wiring module with only the selected generators, and a lock', () => {
    const gen = readFileSync(join(dir, 'src/sigilsmith.gen.ts'), 'utf8');
    expect(gen).toMatch(/GENERATED by `sigilsmith build`/);
    expect(gen).toContain("import('sigilsmith/generators/rings/v1')");
    expect(gen).not.toContain('minidenticons');
    const lock = JSON.parse(readFileSync(join(dir, 'sigilsmith.lock.json'), 'utf8'));
    expect(Object.keys(lock.generators).sort()).toEqual(['grid@1', 'rings@1', 'shapes@1']);
    expect(Object.keys(lock.samples)).toHaveLength(SAMPLE_ITEMS.length);
  });

  it('explain says which rule, which layer, and what a rename does', async () => {
    const env = await explainItems(await loadConfig(undefined, dir), [SAMPLE_ITEMS[2]!]);
    const e = env.data.explanations[0]!;
    expect(e.generator).toMatchObject({ ref: 'rings@1', via: 'rule:0' });
    expect(e.params.find((p) => p.path === 'rings')).toMatchObject({ value: 4, layer: 'generator' });
    expect(e.regeneration.note).toMatch(/renames never change/);
  });

  it('check passes on a fresh build', async () => {
    const env = await check(await loadConfig(undefined, dir));
    expect(env.diagnostics.filter((d) => d.severity === 'error')).toEqual([]);
    expect(env.data.sections).toMatchObject({ config: 'pass', fresh: 'pass', data: 'pass', identity: 'pass', determinism: 'pass', budget: 'pass' });
  });

  it('drift: a renamed key field fails with a one-line fix, and the one-line fix works (B0.5)', async () => {
    const renamed = SAMPLE_ITEMS.map(({ id, ...rest }) => ({ uid: id, ...rest }));
    writeFileSync(join(dir, 'items.json'), JSON.stringify(renamed));
    const env = await check(await loadConfig(undefined, dir), { only: ['data'] });
    const d = env.diagnostics.find((x) => x.code === 'SGS0701')!;
    expect(d.message).toMatch(/key field `id` is missing from 5 of 5/);
    expect(d.fix!.edits).toEqual([{ file: 'sigilsmith.config.json', path: 'key.field', set: 'uid' }]);
    const cfgFile = join(dir, 'sigilsmith.config.json');
    const cfg = JSON.parse(readFileSync(cfgFile, 'utf8'));
    cfg.key.field = 'uid'; // the one-line change
    writeFileSync(cfgFile, JSON.stringify(cfg, null, 2));
    const again = await check(await loadConfig(undefined, dir), { only: ['data', 'fresh'] });
    expect(again.data.sections.data).toBe('pass');
    expect(again.diagnostics.map((x) => x.code)).toEqual(['SGS0703']); // config changed: rebuild the wiring module
  });

  it('identity: a changed rule shows which sample items would change', async () => {
    const d2 = makeProject(BASIC);
    await build(await loadConfig(undefined, d2));
    const cfg = JSON.parse(readFileSync(join(d2, 'sigilsmith.config.json'), 'utf8'));
    cfg.policy.rules[0].use = 'shapes@1';
    writeFileSync(join(d2, 'sigilsmith.config.json'), JSON.stringify(cfg));
    const env = await check(await loadConfig(undefined, d2), { only: ['identity'] });
    expect(env.diagnostics.find((x) => x.code === 'SGS0504')!.where!.items).toEqual(['vid_1', 'vid_2']);
  });

  it('bypass: app code that imports a generator or hard-codes a ref is flagged', async () => {
    writeFileSync(join(dir, 'src/Card.tsx'), "import grid from 'sigilsmith/generators/grid/v1';\nimport { sigil } from './sigilsmith.gen';\nsigil.render(item, { ref: 'grid@1' });\n");
    const env = await check(await loadConfig(undefined, dir), { only: ['bypass'] });
    expect(env.diagnostics.map((d) => d.code).sort()).toEqual(['SGS0705', 'SGS0706']);
  });
});

